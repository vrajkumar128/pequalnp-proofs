import sys, time, random, argparse
sys.path.insert(0, '.')
import synth
ap = argparse.ArgumentParser()
ap.add_argument('-s', type=int, default=19)
ap.add_argument('--shard', type=int, default=None)
ap.add_argument('--mono', action='store_true')
ap.add_argument('--solver', default='kissat404')
ap.add_argument('--extra', type=int, default=0)
ap.add_argument('--seed', type=int, default=1)
ap.add_argument('--implied', action='store_true')
ap.add_argument('--dm', action='store_true')
ap.add_argument('--notlo', type=int, default=None)
ap.add_argument('--nothi', type=int, default=None)
ap.add_argument('--allrows', action='store_true')
ap.add_argument('--singles', action='store_true')
ap.add_argument('--links', action='store_true')
a = ap.parse_args()
rows = synth.critical_rows()
random.seed(a.seed)
if a.extra:
    rest = [t for t in range(1<<synth.N) if t not in rows]
    rows += random.sample(rest, a.extra)
t0 = time.time()
if a.allrows: rows = list(range(1<<synth.N))
if a.singles: rows = rows + [0] + [1<<v for v in range(synth.N)]
enc = synth.Enc(a.s, shard=a.shard, monotone=a.mono, solver=a.solver)
for t in rows: enc.add_row(t)
if a.implied: enc.add_implied_mono(synth.critical_rows())
if a.dm: enc.add_demorgan_rule()
if a.links: enc.add_mono_links()
if a.notlo is not None or a.nothi is not None: enc.limit_nots(a.notlo, a.nothi)
print('built', enc.nv, 'vars rows', len(rows), time.time()-t0, flush=True)
r = enc.S.solve()
print('result', r, 'time', time.time()-t0, flush=True)
if r:
    g = enc.decode(enc.S.get_model())
    print(g)
    print('bad rows', len(synth.check_all(g)))
