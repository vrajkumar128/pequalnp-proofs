"""Lean 4 certificate emitter (the approach of L-meta-651/probe20.lean).

The emitted file states the circuit with the project's definitions and proves, without
`native_decide`:
  * `fan`   : FanInTwo C            (and `mono : Monotone2 C` for the monotone basis,
              `nots : number of NOT gates <= k` for the k-NOT basis)
  * `tabK`  : for all Booleans b0 .. b(n-1), C_K.eval [b0, .., b(n-1)] = spec_K  (by `decide`)
  * `mainK` : HasCircuitSize n spec_K s  (one per output; outputs share one gate list)
The spec of an output is its Lean formula when the target has one (graphs, Boolean sums,
minterm lists), otherwise `tableFun n T` with the explicit truth table T.
"""
import re

from .core import circuit_tables


def _gate(op, ins):
    return '⟨GateOp.%s, [%s]⟩' % (op, ', '.join(str(i) for i in ins))


def _table_list(tt, n):
    return '[' + ', '.join('true' if (tt >> t) & 1 else 'false' for t in range(1 << n)) + ']'


def emit(c, target, basis, s=None, name='Synth', spec='auto'):
    """c: core.Circuit for all outputs of target. Returns the Lean source."""
    n = target.n
    s = c.size if s is None else s
    assert circuit_tables(c) == target.tables, 'circuit does not compute the target'
    ns = re.sub(r'[^A-Za-z0-9_]', '_', name)
    if not ns[0].isalpha():
        ns = 'C' + ns
    bs = ['b%d' % i for i in range(n)]
    blist = '[' + ', '.join(bs) + ']'
    xs = '[' + ', '.join('x %d' % i for i in range(n)) + ']'
    use_formula = spec == 'formula' or (spec == 'auto' and target.formulas)
    L = []
    L.append('import Mathlib')
    L.append('import PEqualNP.Defs')
    L.append('')
    L.append('/-! Generated by circuit_synth. %s, basis %s, %d inputs, %d gates.' % (
        target.desc.replace('-/', '- /'), basis.name(), n, c.size))
    L.append('Every computation is checked by the kernel with `decide` (no native code). -/')
    L.append('')
    L.append('open PEqualNP.CircuitLowerBounds PEqualNP.MetaComplexity')
    L.append('')
    L.append('namespace CircuitSynth.%s' % ns)
    L.append('')
    L.append('def gates : List Gate := [%s]' % ', '.join(_gate(op, ins) for op, ins in c.gates))
    L.append('')
    for k, o in enumerate(c.outputs):
        L.append('def C%d : Circuit := ⟨gates, %d⟩' % (k, o))
    L.append('')
    for k in range(len(c.outputs)):
        L.append('theorem fan%d : FanInTwo C%d := by' % (k, k))
        L.append('  unfold FanInTwo')
        L.append('  simp [C%d, gates]' % k)
        L.append('')
        if basis.max_not == 0:
            L.append('theorem mono%d : Monotone2 C%d := by' % (k, k))
            L.append('  unfold Monotone2')
            L.append('  simp [C%d, gates]' % k)
            L.append('')
    if basis.max_not not in (None, 0):
        L.append('/-- At most %d NOT gates. -/' % basis.max_not)
        L.append('theorem nots : (gates.filter (fun g => match g.op with | GateOp.not => true '
                 '| _ => false)).length ≤ %d := by decide' % basis.max_not)
        L.append('')
    specs = []
    for k in range(len(c.outputs)):
        if use_formula:
            f = target.formulas[k]
            sb = f                                  # in b-variables
            sx = re.sub(r'\bb(\d+)\b', r'x \1', f)   # in x i
            specs.append(('fun x : Fin %d → Bool => %s' % (n, sx), '(%s)' % sb))
        else:
            T = _table_list(target.tables[k], n)
            specs.append(('tableFun %d %s' % (n, T),
                          'tableFun %d %s ![%s]' % (n, T, ', '.join(bs))))
    for k in range(len(c.outputs)):
        fx, fb = specs[k]
        L.append('set_option maxRecDepth 100000 in')
        L.append('set_option maxHeartbeats 0 in')
        L.append(('theorem tab%d : ∀ %s : Bool,' % (k, ' '.join(bs))) if n else
                 ('theorem tab%d :' % k))
        L.append('    C%d.eval %s = %s := by' % (k, blist, fb))
        L.append('  decide')
        L.append('')
        L.append('theorem eval%d (x : Fin %d → Bool) : C%d.eval (List.ofFn x) = (%s) x := by'
                 % (k, n, k, fx))
        if n:
            L.append('  have h : List.ofFn x = %s := by simp [List.ofFn_succ]' % xs)
            L.append('  rw [h, tab%d]' % k)
        else:
            L.append('  rw [List.ofFn_zero, tab%d]' % k)
        if not use_formula:
            L.append('  congr 1')
            L.append('  funext i')
            L.append('  fin_cases i <;> rfl')
        L.append('')
        L.append('theorem main%d : HasCircuitSize %d (%s) %d :=' % (k, n, fx, s))
        L.append('  ⟨C%d, fan%d, by decide, eval%d⟩' % (k, k, k))
        L.append('')
    if len(c.outputs) > 1:
        L.append('/-- All outputs from one shared list of %d gates. -/' % c.size)
        conj = ' ∧ '.join('C%d.eval (List.ofFn x) = (%s) x' % (k, specs[k][0])
                          for k in range(len(c.outputs)))
        L.append('theorem shared : gates.length ≤ %d ∧ ∀ x : Fin %d → Bool, %s :=' % (s, n, conj))
        L.append('  ⟨by decide, fun x => ⟨%s⟩⟩' % ', '.join('eval%d x' % k for k in range(len(c.outputs))))
        L.append('')
    L.append('end CircuitSynth.%s' % ns)
    return '\n'.join(L) + '\n'
